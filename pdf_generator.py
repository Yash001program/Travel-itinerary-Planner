from typing import Any, Dict
from fpdf import FPDF
from storage import convert_currency


def _sanitize_text(text: Any) -> str:
    """Ensures Latin-1 compatibility for standard FPDF core fonts."""
    s = str(text or "")
    replacements = {
        "—": "-",
        "–": "-",
        "’": "'",
        "‘": "'",
        "“": '"',
        "”": '"',
        "•": "*",
        "₹": "INR ",
        "€": "EUR ",
        "¥": "JPY ",
        "£": "GBP ",
    }
    for k, v in replacements.items():
        s = s.replace(k, v)
    return s.encode("latin-1", errors="replace").decode("latin-1")


class TravelGuidePDF(FPDF):
    def header(self):
        self.set_fill_color(15, 76, 92)  # Deep Wanderlust Teal
        self.rect(0, 0, 210, 18, "F")
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(255, 255, 255)
        self.set_y(5)
        self.cell(0, 8, "PERSONALIZED TRAVEL ITINERARY GUIDE | OFFLINE EDITION", align="C")
        self.ln(16)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 120)
        self.cell(
            0,
            10,
            f"Generated by Personalized Travel Itinerary Planner  |  Page {self.page_no()}",
            align="C",
        )


def generate_itinerary_pdf(
    itinerary: Dict[str, Any], preferences: Dict[str, Any]
) -> bytes:
    """Builds a cleanly formatted multi-section PDF with budget summary & emergency checklist."""
    pdf = TravelGuidePDF()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    dest = _sanitize_text(itinerary.get("destination", "Custom Destination"))
    currency = _sanitize_text(itinerary.get("local_currency", "USD"))
    days = itinerary.get("days", [])

    # Title Banner
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(15, 76, 92)
    pdf.cell(0, 11, dest, ln=True)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(80, 80, 80)
    meta = (
        f"Duration: {len(days)} Days  |  Start Date: {preferences.get('start_date', 'Flexible')}  |  "
        f"Party: {preferences.get('party', 'Traveler')}  |  Tier: {preferences.get('budget', 'Moderate')}  |  "
        f"Pace: {preferences.get('pace', 'Moderate')}"
    )
    pdf.cell(0, 6, _sanitize_text(meta), ln=True)
    pdf.ln(4)

    # Calculate Grand Totals
    total_local = sum(
        float(slot.get("cost_local", 0))
        for d in days
        for slot in d.get("slots", [])
    )
    totals = convert_currency(total_local, currency)

    # Budget Summary Box
    pdf.set_fill_color(240, 247, 249)
    pdf.set_draw_color(15, 76, 92)
    pdf.rect(10, pdf.get_y(), 190, 16, "DF")
    pdf.set_xy(14, pdf.get_y() + 4)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(15, 76, 92)
    summary_line = (
        f"ESTIMATED TRIP ACTIVITY BUDGET:  {totals['local']:,.0f} {currency}   |   "
        f"${totals['usd']:,.2f} USD   |   INR {totals['inr']:,}"
    )
    pdf.cell(0, 8, _sanitize_text(summary_line), ln=True)
    pdf.ln(8)

    # Day-by-Day Breakdown
    for day in days:
        day_num = day.get("day_number", 1)
        zone = _sanitize_text(day.get("cluster_zone", "City Center"))
        transit_note = _sanitize_text(day.get("transit_note", ""))

        day_local = sum(float(s.get("cost_local", 0)) for s in day.get("slots", []))
        day_conv = convert_currency(day_local, currency)

        # Day Header Bar
        pdf.set_fill_color(227, 100, 20)  # Warm Terracotta Accent
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(
            0,
            8,
            _sanitize_text(
                f"  DAY {day_num}: {zone}   (Est: {day_conv['local']:,.0f} {currency} / ${day_conv['usd']:.2f})"
            ),
            ln=True,
            fill=True,
        )

        if transit_note:
            pdf.set_font("Helvetica", "I", 9)
            pdf.set_text_color(90, 90, 90)
            pdf.cell(0, 6, f"  Cluster Logistics: {transit_note}", ln=True)

        pdf.ln(1)

        for slot in day.get("slots", []):
            slot_name = _sanitize_text(slot.get("slot_name", ""))
            time_win = _sanitize_text(slot.get("time_window", ""))
            title = _sanitize_text(slot.get("title", ""))
            desc = _sanitize_text(slot.get("description", ""))
            transit = _sanitize_text(slot.get("transit_from_prev", ""))
            cost_loc = float(slot.get("cost_local", 0))
            cost_conv = convert_currency(cost_loc, currency)

            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(25, 25, 25)
            pdf.cell(
                0,
                6,
                _sanitize_text(
                    f"[{time_win}] {slot_name}: {title}  ({cost_conv['local']:,.0f} {currency} / ${cost_conv['usd']:.2f})"
                ),
                ln=True,
            )

            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(60, 60, 60)
            pdf.multi_cell(0, 5, f"   {desc}")
            pdf.set_font("Helvetica", "I", 8.5)
            pdf.set_text_color(15, 76, 92)
            pdf.cell(0, 5, f"   Transit: {transit}", ln=True)
            pdf.ln(1.5)

        pdf.ln(3)

    # Emergency Contact & Pre-Departure Checklist Section
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(15, 76, 92)
    pdf.cell(0, 9, "OFFLINE EMERGENCY CONTACTS & TRAVEL CHECKLIST", ln=True)
    pdf.ln(2)

    em = itinerary.get("emergency_info", {})
    contacts = [
        ("Local Police / General Emergency", em.get("police", "112 / 911")),
        ("Medical & Ambulance Services", em.get("ambulance", "108 / 112")),
        ("24/7 Tourist Assistance Helpline", em.get("tourist_helpline", "Local Tourist Police")),
        ("Embassy / Consular Assistance", "Save local embassy address & 24h duty officer line"),
    ]

    for label, val in contacts:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(30, 30, 30)
        pdf.cell(75, 7, _sanitize_text(f"* {label}:"), border=0)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 7, _sanitize_text(val), ln=True)

    pdf.ln(5)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(227, 100, 20)
    pdf.cell(0, 7, "Essential Safety & Packing Checklist:", ln=True)

    checklist = [
        "[ ] Passport / Government ID + Printed & Offline PDF Copies",
        "[ ] Travel Insurance Policy Number & 24/7 Claims Hotline",
        "[ ] International Roaming / Local eSIM Activated",
        "[ ] Primary & Backup Payment Cards (International Usage Enabled)",
        "[ ] Personal Prescription Medications & Basic First-Aid Kit",
    ] + [f"[ ] Tip: {tip}" for tip in em.get("local_tips", [])]

    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(45, 45, 45)
    for item in checklist:
        pdf.cell(0, 6, _sanitize_text(item), ln=True)

    return bytes(pdf.output())
